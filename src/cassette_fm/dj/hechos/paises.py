def nombre_de_pais(codigo: str, idioma: str) -> str | None:
    """El nombre del país para decirlo en voz alta; `None` si el código no está en la tabla."""
    pais = PAISES.get((codigo or "").upper())
    if pais is None:
        return None
    return pais[0] if idioma == "es" else pais[1]
